const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = process.argv[2] || path.resolve(__dirname, '..');
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root, 'match.js'),'utf8')+'\nthis.api={emptyMatch,cleanMatch,matchErrors,matchHeroes,matchMaps};',ctx);
const {emptyMatch,cleanMatch,matchErrors,matchHeroes,matchMaps} = ctx.api;
const valid = ()=>({map:'kings-row',side:'attack',mine:2,ally:['winston','cassidy','genji','ana','brigitte'],enemy:['sigma','widowmaker','hanzo','baptiste','zenyatta']});
assert.equal(matchErrors(valid()).length,0);
assert.equal(matchErrors({...valid(),map:'',side:''}).length,0,'map is optional');
assert.equal(matchErrors({...valid(),side:''}).length,1,'sided maps require side');
assert.equal(matchErrors({...valid(),mine:null}).length,1);
const dupe=valid();dupe.ally[2]='cassidy';assert(matchErrors(dupe).some(e=>e.includes('두 번')));
const mirror=valid();mirror.enemy=[...mirror.ally];assert.equal(matchErrors(mirror).length,0,'cross-team mirrors allowed');
const broken=cleanMatch({map:'invalid',side:'attack',mine:6,ally:['genji','cassidy','cassidy','ana','ana'],enemy:null});
assert.equal(broken.map,'');assert.equal(broken.side,'');assert.equal(broken.mine,null);assert.equal(broken.ally[0],'');assert.equal(broken.ally[2],'');assert.equal(broken.ally[4],'');
assert.equal(cleanMatch({...valid(),map:'busan',side:'attack'}).side,'');
assert.equal(matchErrors(emptyMatch()).length,3);
assert.equal(new Set(matchHeroes.map(h=>h.id)).size,54);
const bg=JSON.parse(fs.readFileSync(path.join(root, 'match-backgrounds.json'),'utf8'));
assert.equal(matchMaps.length,31);for(const m of matchMaps)assert(bg[m.id]?.startsWith('data:image/webp;base64,'),m.id+' missing background');
console.log('Match setup checks passed: complete/optional map, side, player, duplicate/mirror, corrupted draft, roster and 31 backgrounds.');
